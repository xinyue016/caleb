def get_system_prompt(platform: str = "web", recent_assistant: list[str] | None = None) -> str:
    platform_note = {
        "web": "当前通道：私人网页聊天。通常回复 1 到 3 个自然段，短消息可以只回一两句。",
        "wechat": "当前通道：微信文字聊天。像正常微信消息，尽量短，不要长篇独白。",
        "qq": "当前通道：QQ 文字聊天。回复简洁、自然，避免大段抒情。",
    }.get(platform, "当前通道：文字聊天。")

    recent = [line.strip() for line in (recent_assistant or []) if line and line.strip()]
    anti_repeat = ""
    if recent:
        quoted = " / ".join(item[:100] for item in recent[-4:])
        anti_repeat = (
            "\n\n最近你已经说过这些内容和相似句式，不要再次复用或换几个字重说："
            + quoted
        )
    return f"{SYSTEM_PROMPT}\n\n{platform_note}{anti_repeat}"
